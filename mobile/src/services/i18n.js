// React Context for lightning-fast synchronous re-renders across all screens
export const LanguageContext = React.createContext({
  language: 'en',
  setLanguage: () => {},
  t: (key, fallback) => t(key, fallback),
  formatSyncTime: (timeStr) => formatRelativeTime(timeStr, 'en'),
  formatPhaseMonth: (monthStr) => formatPhaseMonth(monthStr, 'en'),
  formatStageName: (s, short) => formatStageName(s, 'en', short),
  formatOperationName: (s) => formatOperationName(s, 'en'),
  languages: LANGUAGES,
});

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(currentLanguage);

  useEffect(() => {
    const unsub = subscribeLanguage((newLang) => {
      setLang(newLang);
    });
    return unsub;
  }, []);

  const value = useMemo(() => ({
    language: lang,
    setLanguage,
    t: (key, fallback) => t(key, fallback),
    formatSyncTime: (timeStr) => formatRelativeTime(timeStr, lang),
    formatPhaseMonth: (monthStr) => formatPhaseMonth(monthStr, lang),
    formatStageName: (s, short) => formatStageName(s, lang, short),
    formatOperationName: (s) => formatOperationName(s, lang),
    languages: LANGUAGES,
  }), [lang]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}

